#!/usr/bin/env bash
# Vendors the Cargo dependency tree so Fedora/mock and Debian/sbuild can build
# anonify without network access (both builders run offline by default).
#
# Usage, from the repository root:
#   ./packaging/vendor.sh && tar -czf anonify-1.0.0-vendored.tar.gz \
#       --exclude=target --exclude=.git .
#
# The script only writes ./vendor and ./.cargo/config.toml; delete both to get
# back to a normal online build. `Cargo.lock` is committed, so `--locked`
# keeps the vendored set reproducible.
set -euo pipefail

cd "$(dirname "$0")/.."

if ! command -v cargo >/dev/null 2>&1; then
  echo "error: cargo not found" >&2
  exit 1
fi

rm -rf vendor
cargo vendor --locked vendor > /tmp/anonify-vendor-config.toml

mkdir -p .cargo
{
  echo "# Generated by packaging/vendor.sh for offline distro builds."
  cat /tmp/anonify-vendor-config.toml
} > .cargo/config.toml
rm -f /tmp/anonify-vendor-config.toml

echo "vendored into ./vendor; build with: cargo build --release --locked --offline"
